#!/usr/bin/env python3
"""Cut the bottom-screen zh-TW glyph subset out of Cubic 11.

Usage: generate_ui_zh_font.py <Cubic_11.ttf>

Collects every character in the zh column of src/port/port_ui_zh.inc plus
printable ASCII, renders each at the font's 12 px design size without
antialiasing, and writes src/port/port_ui_zh_font_generated.inc.

Font: Cubic 11 by ACh-K, https://github.com/ACh-K/Cubic-11 (fonts/ttf/Cubic_11.ttf),
SIL Open Font License 1.1 -- see docs/legal/Cubic-11-OFL.txt. Requires Pillow.
"""
import pathlib
import re
import sys

from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
STRINGS = ROOT / 'src/port/port_ui_zh.inc'
OUTPUT = ROOT / 'src/port/port_ui_zh_font_generated.inc'
SIZE = 12
ROWS = 14  # em rows 0..13: hanzi ink sits in 1..11, latin descenders reach 13


def wanted_characters():
    text = STRINGS.read_text(encoding='utf-8')
    table = text.split('UI_ZH_STRINGS_BEGIN', 1)[1].split('UI_ZH_STRINGS_END', 1)[0]
    chars = {chr(c) for c in range(0x20, 0x7F)}
    for _, zh in re.findall(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}', table):
        chars.update(zh)
    return sorted(chars, key=ord)


def render(font, ch):
    advance = int(round(font.getlength(ch)))
    x0, y0, _, _ = font.getbbox(ch)
    mask = font.getmask(ch, mode='1')
    width, height = mask.size
    ink = [(x0 + mx, y0 + my) for my in range(height) for mx in range(width) if mask.getpixel((mx, my))]
    # A negative left bearing (latin 'j') would reach into the previous
    # glyph; shift it into the cell and widen the advance to match.
    shift = -min([0] + [x for x, _ in ink])
    rows = [0] * ROWS
    for x, y in ink:
        x += shift
        if not (0 <= x < 16 and 0 <= y < ROWS):
            raise SystemExit(f'glyph U+{ord(ch):04X} ink at ({x}, {y}) leaves the 16x{ROWS} cell')
        rows[y] |= 1 << x
    return advance + shift, rows


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    font = ImageFont.truetype(sys.argv[1], SIZE)
    lines = [
        '/* AUTO-GENERATED by tools/generate_ui_zh_font.py - DO NOT EDIT BY HAND.',
        ' * Subset of Cubic 11 (c) ACh-K, SIL Open Font License 1.1',
        ' * (docs/legal/Cubic-11-OFL.txt), rendered at its 12 px design size.',
        ' * rows[y] bit x = ink at column x of em row y; sorted by code point. */',
        '',
        f'#define UI_ZH_EM {SIZE + 1}',
        f'#define UI_ZH_GLYPH_ROWS {ROWS}',
        '',
        'typedef struct UiZhGlyph {',
        '    uint16_t cp;',
        '    uint8_t advance;',
        '    uint16_t rows[UI_ZH_GLYPH_ROWS];',
        '} UiZhGlyph;',
        '',
        'static const UiZhGlyph kUiZhGlyphs[] = {',
    ]
    for ch in wanted_characters():
        if ord(ch) > 0xFFFF:
            raise SystemExit(f'U+{ord(ch):X} is outside the BMP')
        advance, rows = render(font, ch)
        name = ch if ch.isprintable() and ch not in '\\*/' else ' '
        body = ', '.join(f'0x{r:04X}' for r in rows)
        lines.append(f'    {{ 0x{ord(ch):04X}, {advance}, {{ {body} }} }}, /* {name} */')
    lines.append('};')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUTPUT.relative_to(ROOT)}: {len(lines) - 16} glyphs')


if __name__ == '__main__':
    main()
